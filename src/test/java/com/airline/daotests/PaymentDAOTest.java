package com.airline.daotests;

import com.airline.dao.PaymentDAO;
import com.airline.model.Payment;
import com.airline.util.connection.DatabaseConnection;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class PaymentDAOTest {

    private Connection connection;
    private PaymentDAO paymentDAO;

    private long paymentId;
    private long reservationId;
    private long recordedBy;
    private String transactionRef;

    @BeforeEach
    void setUp() throws SQLException {
        connection = DatabaseConnection.getConnection();
        connection.setAutoCommit(false);

        paymentDAO = new PaymentDAO();

        /*
         * Replace these IDs with valid existing records
         * in your test database.
         */
        reservationId = 25L;
        recordedBy = 17L;

        transactionRef = "TXN-" + UUID.randomUUID()
                .toString().replace("-", "").substring(0, 20);

        Payment payment = new Payment(
                reservationId,
                LocalDateTime.now().withNano(0),
                new BigDecimal("250.00"),
                "USD",
                "CARD",
                "PENDING",
                transactionRef,
                recordedBy
        );

        paymentId = paymentDAO.createPayment(connection, payment);

        assertTrue(paymentId > 0,
                "Payment ID should be generated by Oracle");
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection != null) {
            try {
                connection.rollback();
            } finally {
                connection.close();
            }
        }
    }

    @Test
    void createPaymentShouldGenerateId() {
        assertTrue(paymentId > 0);
    }

    @Test
    void getPaymentByIdShouldReturnPayment() throws SQLException {
        Payment payment = paymentDAO.getPaymentById(
                connection, paymentId);

        assertNotNull(payment);
        assertEquals(paymentId, payment.getPayment_id());
        assertEquals(reservationId, payment.getReservation_id());
        assertEquals(0, new BigDecimal("250.00")
                .compareTo(payment.getAmount()));
        assertEquals("USD", payment.getCurrency());
        assertEquals("CARD", payment.getPayment_method());
        assertEquals("PENDING", payment.getPayment_status());
        assertEquals(transactionRef, payment.getTransaction_ref());
        assertEquals(recordedBy, payment.getRecorded_by());
    }

    @Test
    void getPaymentByIdShouldReturnNullWhenNotFound()
            throws SQLException {
        Payment payment = paymentDAO.getPaymentById(
                connection, -999L);

        assertNull(payment);
    }

    @Test
    void getPaymentsByReservationShouldReturnPayments()
            throws SQLException {
        List<Payment> payments =
                paymentDAO.getPaymentsByReservation(
                        connection, reservationId);

        assertNotNull(payments);
        assertTrue(payments.stream().anyMatch(
                payment -> payment.getPayment_id() == paymentId));
    }

    @Test
    void getPaymentsByReservationShouldReturnEmptyListWhenNone()
            throws SQLException {
        List<Payment> payments =
                paymentDAO.getPaymentsByReservation(
                        connection, -999L);

        assertNotNull(payments);
        assertTrue(payments.isEmpty());
    }

    @Test
    void getAllPaymentsShouldIncludeCreatedPayment()
            throws SQLException {
        List<Payment> payments =
                paymentDAO.getAllPayments(connection);

        assertNotNull(payments);
        assertTrue(payments.stream().anyMatch(
                payment -> payment.getPayment_id() == paymentId));
    }

    @Test
    void updatePaymentStatusShouldUpdateStatus()
            throws SQLException {
        boolean updated = paymentDAO.updatePaymentStatus(
                connection, paymentId, "FAILED");

        assertTrue(updated);

        Payment payment = paymentDAO.getPaymentById(
                connection, paymentId);

        assertNotNull(payment);
        assertEquals("FAILED", payment.getPayment_status());
    }

    @Test
    void updatePaymentStatusShouldReturnFalseWhenNotFound()
            throws SQLException {
        boolean updated = paymentDAO.updatePaymentStatus(
                connection, -999L, "FAILED");

        assertFalse(updated);
    }

    @Test
    void getPaidAmountByReservationShouldReturnPaidAmount()
            throws SQLException {
        paymentDAO.updatePaymentStatus(
                connection, paymentId, "COMPLETED");

        BigDecimal paidAmount =
                paymentDAO.getPaidAmountByReservation(
                        connection, reservationId);

        assertNotNull(paidAmount);
        assertTrue(
                paidAmount.compareTo(new BigDecimal("250.00")) >= 0,
                "Paid amount should include the created payment"
        );
    }

    @Test
    void getPaidAmountByReservationShouldReturnZeroWhenNone()
            throws SQLException {
        BigDecimal paidAmount =
                paymentDAO.getPaidAmountByReservation(
                        connection, -999L);

        assertEquals(0, BigDecimal.ZERO.compareTo(paidAmount));
    }
}