package com.airline.daotests;

import com.airline.dao.CancellationDAO;
import com.airline.model.Cancellation;
import com.airline.util.connection.DatabaseConnection;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.SQLException;
import java.time.LocalDateTime;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class CancellationDAOTest {

    private Connection connection;
    private CancellationDAO cancellationDAO;

    private long cancellationId;
    private long reservationId;
    private long employeeId;

    private Cancellation cancellation;

    @BeforeEach
    void setUp() throws SQLException {
        connection = DatabaseConnection.getConnection();
        connection.setAutoCommit(false);

        cancellationDAO = new CancellationDAO();

        /*
         * Use valid existing IDs from your test database.
         */
        reservationId = 25L;
        employeeId = 17L;

        cancellation = new Cancellation(
                reservationId,
                LocalDateTime.now().withNano(0),
                "Customer requested cancellation",
                employeeId
        );

        cancellationId = cancellationDAO.createCancellation(
                connection, cancellation);

        assertTrue(cancellationId > 0,
                "Cancellation ID should be generated by Oracle");
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection != null) {
            try {
                connection.rollback();
            } finally {
                connection.close();
            }
        }
    }

    @Test
    void createCancellationShouldGenerateId() {
        assertTrue(cancellationId > 0);
    }

    @Test
    void getCancellationByIdShouldReturnCancellation()
            throws SQLException {

        Cancellation result = cancellationDAO.getCancellationById(
                connection, cancellationId);

        assertNotNull(result);
        assertEquals(cancellationId, result.getCancellation_id());
        assertEquals(reservationId, result.getReservation_id());
        assertEquals(employeeId, result.getEmployee_id());
        assertEquals(
                "Customer requested cancellation",
                result.getReason()
        );
    }

    @Test
    void getCancellationByIdShouldReturnNullWhenNotFound()
            throws SQLException {

        Cancellation result = cancellationDAO.getCancellationById(
                connection, -999L);

        assertNull(result);
    }

    @Test
    void getCancellationsByReservationShouldReturnCancellations()
            throws SQLException {

        List<Cancellation> results =
                cancellationDAO.getCancellationsByReservation(
                        connection, reservationId);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getCancellation_id() == cancellationId));
    }

    @Test
    void getCancellationsByReservationShouldReturnEmptyListWhenNone()
            throws SQLException {

        List<Cancellation> results =
                cancellationDAO.getCancellationsByReservation(
                        connection, -999L);

        assertNotNull(results);
        assertTrue(results.isEmpty());
    }

    @Test
    void getAllCancellationsShouldIncludeCreatedCancellation()
            throws SQLException {

        List<Cancellation> results =
                cancellationDAO.getAllCancellations(connection);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getCancellation_id() == cancellationId));
    }

    @Test
    void updateCancellationShouldUpdateExistingRecord()
            throws SQLException {

        Cancellation updatedCancellation = new Cancellation(
                reservationId,
                LocalDateTime.now().withNano(0),
                "Updated cancellation reason",
                employeeId
        );

        boolean updated = cancellationDAO.updateCancellation(
                connection, cancellationId, updatedCancellation);

        assertTrue(updated);

        Cancellation result = cancellationDAO.getCancellationById(
                connection, cancellationId);

        assertNotNull(result);
        assertEquals(
                "Updated cancellation reason",
                result.getReason()
        );
        assertEquals(reservationId, result.getReservation_id());
        assertEquals(employeeId, result.getEmployee_id());
    }

    @Test
    void updateCancellationShouldReturnFalseWhenNotFound()
            throws SQLException {

        Cancellation updatedCancellation = new Cancellation(
                reservationId,
                LocalDateTime.now().withNano(0),
                "Updated reason",
                employeeId
        );

        boolean updated = cancellationDAO.updateCancellation(
                connection, -999L, updatedCancellation);

        assertFalse(updated);
    }
}