package com.airline.daotests;

import com.airline.dao.CheckInDAO;
import com.airline.model.CheckIn;
import com.airline.util.connection.DatabaseConnection;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.SQLException;
import java.time.LocalDateTime;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

class CheckInDAOTest {

    private Connection connection;
    private CheckInDAO checkInDAO;

    private long checkInId;
    private long segmentId;
    private long employeeId;
    private long ticketId;
    private long flightId;

    @BeforeEach
    void setUp() throws SQLException {
        connection = DatabaseConnection.getConnection();
        connection.setAutoCommit(false);

        checkInDAO = new CheckInDAO();


        segmentId = 132L;
        employeeId = 17L;
        ticketId = 31L;
        flightId = 1L;

        CheckIn checkIn = new CheckIn(
                segmentId,
                LocalDateTime.now().withNano(0),
                null,
                "CHECKED_IN",
                employeeId
        );

        checkInId = checkInDAO.createCheckIn(connection, checkIn);

        assertTrue(checkInId > 0,
                "Check-in ID should be generated by Oracle");
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection != null) {
            try {
                connection.rollback();
            } finally {
                connection.close();
            }
        }
    }

    @Test
    void createCheckInShouldGenerateId() {
        assertTrue(checkInId > 0);
        System.out.println(checkInId);
    }

    @Test
    void getCheckInByIdShouldReturnCheckIn() throws SQLException {
        CheckIn result =
                checkInDAO.getCheckInById(connection, checkInId);

        assertNotNull(result);
        System.out.println(result.getSeatId());
        System.out.println(result.getSegmentId());
        System.out.println(result.getCheckinId());
        assertEquals(checkInId, result.getCheckinId());
        assertEquals(segmentId, result.getSegmentId());
        assertEquals(employeeId, result.getEmployeeId());
        assertEquals("CHECKED_IN", result.getStatus());
        assertNull(result.getSeatId());
    }

    @Test
    void getCheckInByIdShouldReturnNullWhenNotFound()
            throws SQLException {
        CheckIn result =
                checkInDAO.getCheckInById(connection, -999L);

        assertNull(result);
    }

    @Test
    void getCheckInsByTicketShouldReturnCheckIns()
            throws SQLException {
        List<CheckIn> results =
                checkInDAO.getCheckInsByTicket(connection, ticketId);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getCheckinId() == checkInId));
    }

    @Test
    void getCheckInsByTicketShouldReturnEmptyListWhenNotFound()
            throws SQLException {
        List<CheckIn> results =
                checkInDAO.getCheckInsByTicket(connection, -999L);

        assertNotNull(results);
        assertTrue(results.isEmpty());
    }

    @Test
    void getCheckInsByFlightShouldReturnCheckIns()
            throws SQLException {
        List<CheckIn> results =
                checkInDAO.getCheckInsByFlight(connection, flightId);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getCheckinId() == checkInId));
    }

    @Test
    void getCheckInsByFlightShouldReturnEmptyListWhenNotFound()
            throws SQLException {
        List<CheckIn> results =
                checkInDAO.getCheckInsByFlight(connection, -999L);

        assertNotNull(results);
        assertTrue(results.isEmpty());
    }

    @Test
    void updateCheckInStatusShouldUpdateStatus()
            throws SQLException {
        boolean updated = checkInDAO.updateCheckInStatus(
                connection, checkInId, "CHECKED_IN");

        assertTrue(updated);

        CheckIn result =
                checkInDAO.getCheckInById(connection, checkInId);

        assertNotNull(result);
        assertEquals("CHECKED_IN", result.getStatus());
    }

    @Test
    void updateCheckInStatusShouldReturnFalseWhenNotFound()
            throws SQLException {
        boolean updated = checkInDAO.updateCheckInStatus(
                connection, -999L, "COMPLETED");

        assertFalse(updated);
    }
}