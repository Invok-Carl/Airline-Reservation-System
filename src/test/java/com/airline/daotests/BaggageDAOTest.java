package com.airline.daotests;

import com.airline.dao.BaggageDAO;
import com.airline.model.Baggage;
import com.airline.util.connection.DatabaseConnection;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class BaggageDAOTest {

    private Connection connection;
    private BaggageDAO baggageDAO;

    private long baggageId;
    private long segmentId;
    private long ticketId;
    private long passengerId;
    private String tagNumber;

    @BeforeEach
    void setUp() throws SQLException {
        connection = DatabaseConnection.getConnection();
        connection.setAutoCommit(false);

        baggageDAO = new BaggageDAO();


        segmentId = 132L;
        ticketId = 31L;
        passengerId = 11111111111111L;

        tagNumber = "BG-" + UUID.randomUUID()
                .toString()
                .replace("-", "")
                .substring(0, 12);

        Baggage baggage = new Baggage(
                tagNumber,
                segmentId,
                new BigDecimal("18.50"),
                "LOADED"
        );

        baggageId = baggageDAO.createBaggage(connection, baggage);

        assertTrue(baggageId > 0,
                "Baggage ID should be generated by Oracle");
    }

    @AfterEach
    void tearDown() throws SQLException {
        if (connection != null) {
            try {
                connection.rollback();
            } finally {
                connection.close();
            }
        }
    }

    @Test
    void createBaggageShouldGenerateId() {
        assertTrue(baggageId > 0);
    }

    @Test
    void getBaggageByIdShouldReturnBaggage() throws SQLException {
        Baggage result =
                baggageDAO.getBaggageById(connection, baggageId);

        assertNotNull(result);
        assertEquals(baggageId, result.getBaggageId());
        assertEquals(tagNumber, result.getTagNumber());
        assertEquals(segmentId, result.getSegmentId());
        assertEquals(
                0,
                new BigDecimal("18.50").compareTo(result.getWeightKg())
        );
        assertEquals("LOADED", result.getStatus());
    }

    @Test
    void getBaggageByIdShouldReturnNullWhenNotFound()
            throws SQLException {
        Baggage result =
                baggageDAO.getBaggageById(connection, -999L);

        assertNull(result);
    }

    @Test
    void getBaggageByTicketShouldReturnBaggage()
            throws SQLException {
        List<Baggage> results =
                baggageDAO.getBaggageByTicket(connection, ticketId);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getBaggageId() == baggageId));
    }

    @Test
    void getBaggageByTicketShouldReturnEmptyListWhenNotFound()
            throws SQLException {
        List<Baggage> results =
                baggageDAO.getBaggageByTicket(connection, -999L);

        assertNotNull(results);
        assertTrue(results.isEmpty());
    }

    @Test
    void getBaggageByPassengerShouldReturnBaggage()
            throws SQLException {
        List<Baggage> results =
                baggageDAO.getBaggageByPassenger(
                        connection, passengerId);

        assertNotNull(results);
        assertTrue(results.stream().anyMatch(
                item -> item.getBaggageId() == baggageId));
    }

    @Test
    void getBaggageByPassengerShouldReturnEmptyListWhenNotFound()
            throws SQLException {
        List<Baggage> results =
                baggageDAO.getBaggageByPassenger(connection, -999L);

        assertNotNull(results);
        assertTrue(results.isEmpty());
    }

    @Test
    void updateBaggageStatusShouldUpdateStatus()
            throws SQLException {
        boolean updated = baggageDAO.updateBaggageStatus(
                connection, baggageId, "LOADED");

        assertTrue(updated);

        Baggage result =
                baggageDAO.getBaggageById(connection, baggageId);

        assertNotNull(result);
        assertEquals("LOADED", result.getStatus());
    }

    @Test
    void updateBaggageStatusShouldReturnFalseWhenNotFound()
            throws SQLException {
        boolean updated = baggageDAO.updateBaggageStatus(
                connection, -999L, "LOADED");

        assertFalse(updated);
    }

    @Test
    void deleteBaggageShouldDeleteBaggage() throws SQLException {
        boolean deleted =
                baggageDAO.deleteBaggage(connection, baggageId);

        assertTrue(deleted);
        assertNull(baggageDAO.getBaggageById(connection, baggageId));
    }

    @Test
    void deleteBaggageShouldReturnFalseWhenNotFound()
            throws SQLException {
        boolean deleted =
                baggageDAO.deleteBaggage(connection, -999L);

        assertFalse(deleted);
    }
}